return function(mod)
  local function loadSibling(file)
    local body, readErr = mod:read(file)
    assert(body, readErr)
    local chunk, err = loadstring(body, "@" .. mod.path .. "/" .. file)
    assert(chunk, err)
    return chunk()
  end
  local function boot(label, fn)
    local ok, err = pcall(fn)
    if not ok then
      mod.log:warn("poke-ecology: %s failed: %s", label, tostring(err))
    end
    return ok
  end
  local options = loadSibling("data/options.lua")
  assert(type(options) == "table", "poke-ecology: data/options.lua must return a table")
  mod.options:define(options)
  boot("rules", function() mod.exports.peRules = loadSibling("data/rules.lua") end)
  boot("time_buckets", function() mod.exports.peBuckets = loadSibling("data/time_buckets.lua") end)
  boot("terrains", function() mod.exports.peTerrains = loadSibling("data/terrains.lua") end)
  boot("slot_templates", function() mod.exports.peSlots = loadSibling("data/slot_templates.lua") end)
  boot("curves", function() mod.exports.peCurves = loadSibling("data/curves.lua") end)
  boot("areas", function() mod.exports.peAreas = loadSibling("data/areas.lua") end)
  boot("modifiers", function() mod.exports.peModifiers = loadSibling("data/modifiers.lua") end)
  boot("overrides", function() mod.exports.peOverrides = loadSibling("data/overrides.lua") end)
  boot("types", function() mod.exports.peTypeIds = loadSibling("data/types.lua") end)
  boot("legendaries", function()
    local t = loadSibling("data/legendaries.lua")
    assert(type(t) == "table", "poke-ecology: data/legendaries.lua must return a table")
    mod.exports.peLegendaries = t
  end)
  boot("dex_to_species", function()
    local t = loadSibling("data/dex_to_species.lua")
    assert(type(t) == "table", "poke-ecology: data/dex_to_species.lua must return a table")
    mod.exports.peDexToSpecies = t
  end)
  boot("rng", function() loadSibling("logic/rng.lua")(mod) end)
  boot("lines", function() loadSibling("logic/lines.lua")(mod) end)
  boot("bands", function() loadSibling("logic/bands.lua")(mod) end)
  boot("admit", function() loadSibling("logic/admit.lua")(mod) end)
  boot("score", function() loadSibling("logic/score.lua")(mod) end)
  boot("population", function() loadSibling("logic/population.lua")(mod) end)
  boot("stage", function() loadSibling("logic/stage.lua")(mod) end)
  boot("overlay", function() loadSibling("logic/overlay.lua")(mod) end)
  boot("roll", function() loadSibling("logic/roll.lua")(mod) end)
  boot("source", function() loadSibling("adapter/source.lua")(mod) end)
  boot("urtc", function() loadSibling("adapter/urtc.lua")(mod) end)
  boot("context", function() loadSibling("adapter/context.lua")(mod) end)
  boot("hooks", function() loadSibling("adapter/hooks.lua")(mod) end)
  boot("natmap", function() loadSibling("adapter/natmap.lua")(mod) end)
  boot("untamed", function() loadSibling("adapter/untamed.lua")(mod) end)
  boot("diag", function() loadSibling("adapter/diag.lua")(mod) end)
  mod.log:info("poke-ecology: loaded (line-first seeded ecology)")
end
